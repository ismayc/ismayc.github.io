#!/usr/bin/env bash
# Regenerate the GitHub Pages proxy block in _redirects.
#
# Every ismayc repo with a GitHub Pages site gets two Netlify rules so that
# chesterismay.com/<repo>/... serves the same page as ismayc.github.io/<repo>/...
# (a 200 rewrite is a proxy: Netlify fetches the page and serves it under this
# domain). The block sits between the two marker lines; everything outside the
# markers is kept as is. Run from anywhere, needs the gh CLI logged in:
#
#   bash scripts/pages-proxy-rules.sh
#
# The workflow .github/workflows/pages-proxy-rules.yaml runs it weekly and
# commits and deploys when a repo gained or lost a Pages site.
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
redirects="$repo_root/_redirects"
start="# BEGIN github-pages-proxy (generated by scripts/pages-proxy-rules.sh)"
end="# END github-pages-proxy"

edge_fn="$repo_root/netlify/edge-functions/pages-slash.ts"

# Public repos only, so the call works with the Actions token too (the weekly
# workflow .github/workflows/pages-proxy-rules.yaml runs this). A private repo
# with a Pages site would need a user token and user/repos?affiliation=owner.
names="$(
  gh api --paginate "users/ismayc/repos?per_page=100" \
    --jq '.[] | select(.has_pages and (.archived | not)) | .name' |
  grep -vx 'ismayc.github.io' | sort -f
)"

rules="$(
  printf '%s\n' "$names" |
  while read -r name; do
    # One splat rule per repo. Netlify ignores the trailing slash when it
    # matches a rule, so this also matches the bare /<repo>, and a separate
    # bare rule that redirects to /<repo>/ loops (seen October 23, 2026). The
    # bare path must still redirect to the slash form, as GitHub Pages does, or
    # the page's relative links (sheet.css) resolve at the site root; the
    # edge function netlify/edge-functions/pages-slash.ts does that.
    printf '/%s/*  https://ismayc.github.io/%s/:splat  200\n' "$name" "$name"
  done
)"

block="$start
# Each repo's site stays deployed by GitHub Pages; these rules only make it
# reachable at the same path on chesterismay.com. No date here on purpose:
# the weekly workflow commits only when the output changes.
$rules
$end"

if grep -qF "$start" "$redirects"; then
  python3 - "$redirects" "$start" "$end" "$block" <<'PY'
import sys
path, start, end, block = sys.argv[1:]
text = open(path).read()
i = text.index(start)
j = text.index(end, i) + len(end)
open(path, "w").write(text[:i] + block + text[j:])
PY
else
  printf '\n%s\n' "$block" >> "$redirects"
fi
echo "wrote $(printf '%s\n' "$rules" | grep -c '^/') rules to $redirects"

# The edge function. A repo named like one of this site's own pages (talks,
# workshops) is left out: the bare path is the site's page there.
bare="$(
  printf '%s\n' "$names" |
  while read -r name; do
    [ -e "$repo_root/$name.qmd" ] || printf '  "%s",\n' "$name"
  done
)"
mkdir -p "$(dirname "$edge_fn")"
cat > "$edge_fn" <<EOF
// Generated by scripts/pages-proxy-rules.sh. Do not edit.
//
// The GitHub Pages sites proxied by the rules in _redirects must be entered
// at /<repo>/ (with the slash), or their relative links resolve at the site
// root. GitHub Pages redirects the bare path itself; Netlify's redirect rules
// cannot (a rule for /<repo> also matches /<repo>/ and loops), so this edge
// function does it. Only the paths listed in config run it.
const repos = [
$bare
];

export default async (request: Request, context: { next: () => Promise<Response> }) => {
  const url = new URL(request.url);
  if (!url.pathname.endsWith("/") && repos.includes(url.pathname.slice(1))) {
    url.pathname += "/";
    return Response.redirect(url.toString(), 301);
  }
  return context.next();
};

export const config = { path: repos.map((name) => "/" + name) };
EOF
echo "wrote $(printf '%s\n' "$bare" | grep -c '"') paths to $edge_fn"
