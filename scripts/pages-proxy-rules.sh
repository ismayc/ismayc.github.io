#!/usr/bin/env bash
# Regenerate the GitHub Pages proxy block in _redirects.
#
# Every ismayc repo with a GitHub Pages site gets two Netlify rules so that
# chesterismay.com/<repo>/... serves the same page as ismayc.github.io/<repo>/...
# (a 200 rewrite is a proxy: Netlify fetches the page and serves it under this
# domain). The block sits between the two marker lines; everything outside the
# markers is kept as is. Run from anywhere, needs the gh CLI logged in:
#
#   bash scripts/pages-proxy-rules.sh
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
redirects="$repo_root/_redirects"
start="# BEGIN github-pages-proxy (generated by scripts/pages-proxy-rules.sh)"
end="# END github-pages-proxy"

rules="$(
  gh api --paginate "user/repos?affiliation=owner&per_page=100" \
    --jq '.[] | select(.has_pages and (.archived | not)) | .name' |
  grep -vx 'ismayc.github.io' | sort -f |
  while read -r name; do
    # A repo named like one of this site's own pages (talks, workshops) keeps
    # the site's page at the bare path; only the paths below it are proxied.
    if [ -e "$repo_root/$name.qmd" ]; then
      printf '# /%s is this site'"'"'s own page\n' "$name"
    else
      printf '/%s    https://ismayc.github.io/%s/        200\n' "$name" "$name"
    fi
    printf '/%s/*  https://ismayc.github.io/%s/:splat  200\n' "$name" "$name"
  done
)"

block="$start
# Updated $(date +%Y-%m-%d). Each repo's site stays deployed by GitHub Pages;
# these rules only make it reachable at the same path on chesterismay.com.
$rules
$end"

if grep -qF "$start" "$redirects"; then
  python3 - "$redirects" "$start" "$end" "$block" <<'PY'
import sys
path, start, end, block = sys.argv[1:]
text = open(path).read()
i = text.index(start)
j = text.index(end, i) + len(end)
open(path, "w").write(text[:i] + block + text[j:])
PY
else
  printf '\n%s\n' "$block" >> "$redirects"
fi
echo "wrote $(printf '%s\n' "$rules" | grep -c '^/') rules to $redirects"
